// Generate the natural 24-egg nest layouts used by web/kitchen-golden.js.
// Usage: node tools/build-kitchen-egg-layout.mjs  (writes web/kitchen-egg-nests.js)
// Eggs are placed by best-candidate sampling inside each bed's rounded footprint,
// with depth compressed like the art's perspective, so the pile reads as one
// clustered nest instead of rows. Output is sorted back to front: drawing order
// and the front-to-back hit order in app.js therefore agree.
const BEDS=[
 // cx, back and front contact lines, half widths at back/front, front egg height (design units)
 {cx:196,back:336,front:392,halfBack:84,halfFront:104,eggH:44,seed:11},
 {cx:196,back:308,front:387,halfBack:97,halfFront:116,eggH:46,seed:23},
 {cx:196,back:313,front:383,halfBack:95,halfFront:113,eggH:45,seed:37},
 {cx:198,back:325,front:392,halfBack:91,halfFront:107,eggH:44,seed:53},
];
const ASPECT=80/86; // visible egg width / height of the original egg sprite
function rng(seed){return ()=>{seed|=0;seed=seed+0x6D2B79F5|0;let t=Math.imul(seed^seed>>>15,1|seed);t=t+Math.imul(t^t>>>7,61|t)^t;return((t^t>>>14)>>>0)/4294967296;};}
function layout(bed){
 const random=rng(bed.seed),depth=bed.front-bed.back,points=[];
 const half=t=>bed.halfBack+(bed.halfFront-bed.halfBack)*t;
 const inside=(u,t)=>Math.abs(u)**2.4+Math.abs(2*t-1)**2.4<=1;
 const candidate=()=>{for(;;){const t=random(),u=random()*2-1;if(inside(u,t))return {t,x:bed.cx+u*half(t),y:bed.back+t*depth};}};
 // Distance in "egg widths", with depth stretched to match the drawn perspective.
 const metric=(a,b)=>Math.hypot(a.x-b.x,(a.y-b.y)*2.2)/(bed.eggH*ASPECT*(.84+.16*(a.t+b.t)/2));
 for(let i=0;i<24;i++){
  let best=null,bestScore=-1;
  for(let k=0;k<40;k++){const c=candidate(),score=points.length?Math.min(...points.map(p=>metric(p,c))):1;if(score>bestScore){best=c;bestScore=score;}}
  points.push(best);
 }
 return points.map(p=>{
  const u=(p.x-bed.cx)/half(p.t),mound=Math.max(0,1-u*u-(2*p.t-1)**2*.7);
  const scale=(.84+.16*p.t)*(.95+random()*.1),rot=(random()*2-1)*11;
  return {x:+p.x.toFixed(1),y:+(p.y-5*mound).toFixed(1),scale:+scale.toFixed(3),rot:+rot.toFixed(1)};
 }).sort((a,b)=>a.y-b.y).map(({x,y,scale,rot})=>[x,y,scale,rot]);
}
const nests=BEDS.map(b=>({eggH:b.eggH,floor:b.front,eggs:layout(b)}));
const {writeFileSync}=await import('node:fs');
writeFileSync(new URL('../web/kitchen-egg-nests.js',import.meta.url),`// Generated by tools/build-kitchen-egg-layout.mjs. Per kitchen level: front egg height,
// lowest contact line and 24 eggs [bottom-centre x, bottom y, scale, tilt°], back to front.
export const EGG_ASPECT=${80/86};
export const NESTS=${JSON.stringify(nests)};
`);
console.log('wrote web/kitchen-egg-nests.js');
